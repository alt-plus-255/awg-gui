func T(locale, key string) string {
	if locale != "ru" {
		locale = "en"
	}
	if m, ok := messages[locale][key]; ok {
		return m
	}
	if m, ok := messages["en"][key]; ok {
		return m
	}
	return key
}

func Tf(locale, key string, vars map[string]string) string {
	s := T(locale, key)
	for k, v := range vars {
		s = strings.ReplaceAll(s, ":"+k, v)
	}
	return s
}
